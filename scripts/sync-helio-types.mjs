#!/usr/bin/env node
// Copies a seed set of ts-rs generated types (and their transitive `import type` closure)
// from the helio repo at origin/main into src/engine/types/.
// Usage: node scripts/sync-helio-types.mjs [--repo D:/nahdi/code/sonushub/helio] [--ref origin/main]
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.resolve(here, "../src/engine/types");
const args = process.argv.slice(2);
const opt = (name, def) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : def;
};
const repo = opt("--repo", process.env.HELIO_REPO || "D:/nahdi/code/sonushub/helio");
const ref = opt("--ref", "origin/main");
const GEN = "frontend/src/lib/generated";

const SEED = [
  "SimulationInput", "SimulationOutput", "ConditionSet", "Scene", "StageSummary",
  "StringingReport", "WireSchedule", "SunPositionDay", "IrrResult", "MonthlyYieldSummary",
  "Circuit", "HorizonProfile", "SiteSummary", "ShortCircuitReport", "EarthingReport",
  "LightningReport", "ProtectionCoordinationReport", "ComplianceReport", "SavedConditionSet", "WeatherDatasetCreated", "WeatherDatasetSummary",
  "DocumentedDefaults", "UncertaintyReport", "WeatherMeta", "AutoCircuitRequest", "AutoCircuitResponse", "ExportLimitationMode",
  // weather sources panel
  "WeatherSeriesSummary", "WeatherSeriesCreated", "WeatherSeriesMember", "WeatherSourceComparison", "WeatherComparisonEntry",
  "WeatherDatasetDetail", "MonthlyWeatherSummary", "WeatherQcReport", "CsvMapping",
];

const git = (...a) => execFileSync("git", ["-C", repo, ...a], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
const sha = git("rev-parse", "--short", ref).trim();

const seen = new Map();
const queue = [...SEED];
const missing = [];
while (queue.length) {
  const name = queue.pop();
  if (seen.has(name)) continue;
  let src;
  try {
    src = git("show", `${ref}:${GEN}/${name}.ts`);
  } catch {
    missing.push(name);
    seen.set(name, null);
    continue;
  }
  seen.set(name, src);
  for (const m of src.matchAll(/from\s+"\.\/([A-Za-z0-9_]+)"/g)) queue.push(m[1]);
}

fs.mkdirSync(outDir, { recursive: true });
// Remove only previously generated files; hand-written ones (local.ts) are kept.
for (const f of fs.readdirSync(outDir)) {
  const full = path.join(outDir, f);
  if (f.endsWith(".ts") && fs.readFileSync(full, "utf8").startsWith("// Generated by scripts/sync-helio-types")) fs.rmSync(full);
}
const header = `// Generated by scripts/sync-helio-types.mjs from helio ${sha} (${ref}). Do not edit; run \`npm run sync:helio-types\`.\n`;
const names = [];
for (const [name, src] of seen) {
  if (src == null) continue;
  names.push(name);
  fs.writeFileSync(path.join(outDir, `${name}.ts`), header + src.replace(/^\/\/ This file was generated[^\n]*\n/, ""));
}
names.sort();
fs.writeFileSync(
  path.join(outDir, "index.ts"),
  header + names.map((n) => `export type { ${n} } from "./${n}";`).join("\n") + "\n",
);
fs.writeFileSync(path.join(outDir, "HELIO_SHA.ts"), `export const HELIO_TYPES_SHA = ${JSON.stringify(sha)};\n`);
console.log(`helio ${sha}: wrote ${names.length} types to ${path.relative(process.cwd(), outDir)}`);
if (missing.length) console.log(`not generated in helio (define in src/engine/types/local.ts): ${missing.join(", ")}`);
